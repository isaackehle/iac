#!/usr/bin/env bash
# scripts/gen-env.sh — generate general/.env and <stack>/.env from the central
# secrets file, and render any <stack>/*.tmpl files.
#
# Secrets (Tailscale auth keys, passwords, API keys, ...) live in a single
# file outside this repo — see iac-secrets.env.example for the format and
# scripts/lib.sh for the default path (IAC_SECRETS_FILE). This script never
# touches that file; it only reads it.
#
# Usage:
#   scripts/gen-env.sh <stack>          # generate general/.env + <stack>/.env + render templates
#   scripts/gen-env.sh --all            # do the above for every stack
#
# Generated output (.env files, and any *.tmpl -> stripped-suffix file) is
# gitignored and safe to scp to the NAS as-is.
#
# Why .env: This matches docker compose's default behavior (it auto-loads
# .env if present), and also works with Portainer's "Load variables from
# .env file" button. The .env files are pushed to the NAS and referenced
# explicitly in the docker-compose.yml via env_file directive.
#
# Why general/.env: Contains global defaults (TZ, TS_AUTHKEY, NAS_LAN_IP,
# ADMIN_EMAIL) shared across all stacks. Pushed to
# /volume1/docker/stacks/config/global.env on the NAS.
#
# Why <stack>/.env: Contains stack-specific variables (service credentials,
# Tailscale hostname, etc.). Pushed to
# /volume1/docker/stacks/config/<stack>/service.env on the NAS.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib.sh
source "$ROOT_DIR/scripts/lib.sh"

usage() {
  echo "Usage: $0 <stack> | --all" >&2
  echo "  Generates general/.env and <stack>/.env from the secrets file." >&2
  exit 1
}

# resolve_value KEY — look up KEY in the secrets file (stack-specific then
# global), expand ${VAR} references, and return the value.
resolve_value() {
  local key="$1" stack="$2"
  local value=""

  # Special handling: stack-specific TS_AUTHKEY_<STACK> overrides global.
  if [[ "$key" == "TS_AUTHKEY" ]]; then
    local stack_key
    stack_key="$(get_secret_value "TS_AUTHKEY_$(echo "$stack" | tr '[:lower:]' '[:upper:]')")"
    [[ -n "$stack_key" ]] && echo "$stack_key" && return 0
  fi

  # TS_CERT_DOMAIN: derive from stack name + TS_TAILNET_DOMAIN.
  if [[ "$key" == "TS_CERT_DOMAIN" ]]; then
    local tailnet
    tailnet="$(get_secret_value "TS_TAILNET_DOMAIN")"
    if [[ -n "$tailnet" ]]; then
      echo "${stack}.${tailnet}"
      return 0
    fi
  fi

  value="$(get_secret_value "$key")"
  echo "$value"
}

# expand_refs VALUE — expand any ${VAR} or ${VAR:-default} references in a
# string using the secrets file.
expand_refs() {
  local value="$1"
  local ref ref_val ref_default ref_text
  while [[ "$value" =~ \$\{([A-Z_][A-Z0-9_]*)(:-([^}]*))?\} ]]; do
    ref_text="${BASH_REMATCH[0]}"
    ref="${BASH_REMATCH[1]}"
    ref_default="${BASH_REMATCH[3]}"
    ref_val="$(get_secret_value "$ref")"
    if [[ -z "$ref_val" ]]; then
      [[ -n "${BASH_REMATCH[2]}" ]] || break
      ref_val="$ref_default"
    fi
    value="${value//"$ref_text"/$ref_val}"
  done
  echo "$value"
}

gen_global() {
  local sample="general/.env.sample"
  if [[ ! -f "$sample" ]]; then
    echo "==> general: no $sample, skipping"
    return 0
  fi

  if [[ ! -f "$IAC_SECRETS_FILE" ]]; then
    echo "ERROR: secrets file not found at $IAC_SECRETS_FILE" >&2
    exit 1
  fi

  local out="general/.env"
  {
    echo "# Generated by scripts/gen-env.sh from $IAC_SECRETS_FILE"
    echo "# Do not edit by hand — edit the secrets file and regenerate instead."
    echo "# Regenerate with: scripts/gen-env.sh --all"
  } >"$out"

  local missing=()
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" =~ ^[[:space:]]*# ]] && continue
    [[ "$line" =~ ^[[:space:]]*$ ]] && continue
    [[ "$line" == *"="* ]] || continue

    local key="${line%%=*}"
    local default_val="${line#*=}"
    local value

    value="$(resolve_value "$key" "general")"

    # Expand ${VAR} references in the value.
    value="$(expand_refs "$value")"

    # If no secret found, fall back to the default from the sample.
    if [[ -z "$value" ]]; then
      value="$default_val"
    fi

    echo "${key}=${value}" >>"$out"

    case "$value" in
      ""|*changeme*|*CHANGE_ME*|tskey-auth-xxxx*|tskey-...|*'${'*|*xxxxxxxx*)
        missing+=("$key")
        ;;
    esac
  done <"$sample"

  echo "==> general: wrote $out"
  if [[ "${#missing[@]}" -gt 0 ]]; then
    echo "    ⚠ still unset/placeholder: ${missing[*]}"
    echo "    add these to $IAC_SECRETS_FILE and re-run"
  fi
}

gen_one() {
  local stack="$1"
  require_stack "$stack"

  if [[ ! -f "$IAC_SECRETS_FILE" ]]; then
    echo "ERROR: secrets file not found at $IAC_SECRETS_FILE" >&2
    echo "Copy iac-secrets.env.example there and fill in real values first." >&2
    exit 1
  fi

  render_templates "$stack"

  # Generate global env (once, even when called per-stack).
  gen_global

  local example="$stack/.env.example"
  if [[ ! -f "$example" ]]; then
    echo "==> $stack: no .env.example, nothing to generate"
    return 0
  fi

  local out="$stack/.env"
  {
    echo "# Generated by scripts/gen-env.sh from $IAC_SECRETS_FILE"
    echo "# Do not edit by hand — edit the secrets file and regenerate instead."
    echo "# Regenerate with: scripts/gen-env.sh $stack"
  } >"$out"

  local missing=()
  while IFS= read -r line || [[ -n "$line" ]]; do
    # skip blank lines and comments
    [[ "$line" =~ ^[[:space:]]*# ]] && continue
    [[ "$line" =~ ^[[:space:]]*$ ]] && continue
    [[ "$line" == *"="* ]] || continue

    local key="${line%%=*}"
    local default_val="${line#*=}"
    local value=""

    value="$(resolve_value "$key" "$stack")"

    if [[ -z "$value" ]]; then
      value="$default_val"
    fi

    # Expand any ${VAR} or ${VAR:-default} references.
    value="$(expand_refs "$value")"

    echo "${key}=${value}" >>"$out"

    case "$value" in
      ""|*changeme*|*CHANGE_ME*|tskey-auth-xxxx*|tskey-...|*'${'*|*xxxxxxxx*)
        missing+=("$key")
        ;;
    esac
  done <"$example"

  echo "==> $stack: wrote $out"
  if [[ "${#missing[@]}" -gt 0 ]]; then
    echo "    ⚠ still unset/placeholder: ${missing[*]}"
    echo "    add these to $IAC_SECRETS_FILE and re-run"
  fi
}

[[ $# -eq 1 ]] || usage

cd "$ROOT_DIR"

if [[ "$1" == "--all" ]]; then
  while IFS= read -r s; do
    gen_one "$s"
  done < <(enabled_stacks)
else
  gen_one "$1"
fi
